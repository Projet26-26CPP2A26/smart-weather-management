-- Schéma Oracle - Module 3 : Gestion des Relevés Météo & Attestations
-- (si une ancienne version existe : DROP TABLE ATTESTATION; DROP TABLE RELEVE_METEO; DROP SEQUENCE SEQ_RELEVE; ...)
CREATE SEQUENCE SEQ_RELEVE      START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE SEQ_ATTESTATION START WITH 1 INCREMENT BY 1 NOCACHE;

CREATE TABLE STATION (
    ID_STATION NUMBER        PRIMARY KEY,
    NOM        VARCHAR2(100) NOT NULL,
    LATITUDE   NUMBER(9,6)   NOT NULL,
    LONGITUDE  NUMBER(9,6)   NOT NULL
);

CREATE TABLE RELEVE_METEO (
    ID_RELEVE     NUMBER       PRIMARY KEY,
    ID_STATION    NUMBER       NOT NULL REFERENCES STATION(ID_STATION),
    HORODATAGE    TIMESTAMP    NOT NULL,
    TEMPERATURE   NUMBER(5,2),
    HUMIDITE      NUMBER(5,2)  CHECK (HUMIDITE BETWEEN 0 AND 100),
    PRESSION      NUMBER(7,2),
    VITESSE_VENT  NUMBER(6,2)  CHECK (VITESSE_VENT >= 0),
    PRECIPITATION NUMBER(6,2)  DEFAULT 0 CHECK (PRECIPITATION >= 0),
    MODE_COLLECTE VARCHAR2(10) DEFAULT 'Automatique' CHECK (MODE_COLLECTE IN ('Automatique','Manuel'))
);
CREATE INDEX IDX_RELEVE_STATION_DATE ON RELEVE_METEO (ID_STATION, HORODATAGE);

CREATE TABLE ATTESTATION (
    ID_ATTESTATION  NUMBER        PRIMARY KEY,
    NUMERO          VARCHAR2(20)  NOT NULL UNIQUE,
    DEMANDEUR       VARCHAR2(150) NOT NULL,
    LIEU            VARCHAR2(200) NOT NULL,
    LATITUDE        NUMBER(9,6)   NOT NULL,
    LONGITUDE       NUMBER(9,6)   NOT NULL,
    DATE_DEBUT      DATE          NOT NULL,
    DATE_FIN        DATE          NOT NULL,
    ID_STATION      NUMBER        REFERENCES STATION(ID_STATION),
    STATUT          VARCHAR2(12)  DEFAULT 'EN_COURS'
                    CHECK (STATUT IN ('EN_COURS','DELIVREE','REFUSEE','ANNULEE')),
    DATE_DEMANDE    TIMESTAMP     DEFAULT SYSTIMESTAMP,
    DATE_TRAITEMENT TIMESTAMP
);

